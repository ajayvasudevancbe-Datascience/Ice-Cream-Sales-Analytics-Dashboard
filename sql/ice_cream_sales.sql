# 🍦 Ice Cream Sales Analysis — SQL

## 📌 Project Overview

A SQL-based data analysis project to analyze **ice cream sales, product performance, revenue, store performance, and customer purchasing patterns**.

The project uses **MySQL** to transform sales data into meaningful business insights.

---

## 🛠️ Tools & Technologies

- MySQL
- SQL
- Aggregate Functions
- GROUP BY & ORDER BY
- CASE Statements
- Window Functions
- Data Analysis

